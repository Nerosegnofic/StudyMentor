  // ── Helpers ───────────────────────────────────────────────────────────────

  static List<AvatarItem> byCategory(ItemCategory cat) =>
      all.where((i) => i.category == cat).toList();

  static AvatarItem? findById(String id) {
    try {
      return all.firstWhere((i) => i.id == id);
    } catch (_) {
      return null;
    }
  }

  /// Free starter items the student owns automatically.
  static Set<String> get starterItemIds =>
      all.where((i) => i.isFree).map((i) => i.id).toSet();
}
